#!/usr/bin/env bash
# LabSecurity initialization: the only step before `docker compose up -d`.
#
# - Creates the config directory (mode 700) with one secret file per service group (mode 600). Location: see
#   scripts/lib/paths.sh (Linux/WSL2 ~/.config/labsecurity, macOS ~/Library/Application Support/LabSecurity/config,
#   or $LABSEC_HOME/config).
# - Generates the repository .env with NON-secret settings only (config dir and ports).
# - Idempotent: existing secret files are never overwritten (rotating them would lock out the databases).
# - Never prints secret values.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib/paths.sh
. "$ROOT/scripts/lib/paths.sh"
labsec_resolve_paths
CONFIG_DIR="$LABSEC_CONFIG_DIR"
SONAR_PORT="${SONAR_PORT:-19000}"
DD_PORT="${DD_PORT:-19080}"

umask 077
mkdir -p "$CONFIG_DIR"
chmod 700 "$CONFIG_DIR"

rand() { # URL-safe random string without characters that need escaping in URLs or shells
  if command -v python3 >/dev/null 2>&1; then
    python3 -c 'import secrets,sys; print(secrets.token_hex(int(sys.argv[1])))' "${1:-24}"
  else
    openssl rand -hex "${1:-24}"
  fi
}

write_secret_file() { # name, content
  local file="$CONFIG_DIR/$1"
  if [[ -s "$file" ]]; then
    echo "kept     $file"
  else
    printf '%s\n' "$2" >"$file"
    echo "created  $file"
  fi
  chmod 600 "$file"
}

sonar_db_pw="$(rand 24)"
dd_db_pw="$(rand 24)"
dd_admin_pw="$(rand 18)"
sonar_admin_pw="Lab-$(rand 18)"

# If the files already exist, reuse their values so related files stay consistent.
read_var() { # file, key
  [[ -s "$CONFIG_DIR/$1" ]] && sed -n "s/^$2=//p" "$CONFIG_DIR/$1" | head -n1 || true
}
existing="$(read_var sonar-db.vars POSTGRES_PASSWORD)"; [[ -n "$existing" ]] && sonar_db_pw="$existing"
existing="$(read_var dd-db.vars POSTGRES_PASSWORD)"; [[ -n "$existing" ]] && dd_db_pw="$existing"
existing="$(read_var defectdojo.vars DD_ADMIN_PASSWORD)"; [[ -n "$existing" ]] && dd_admin_pw="$existing"
existing="$(read_var cli.vars SONAR_ADMIN_PASSWORD)"; [[ -n "$existing" ]] && sonar_admin_pw="$existing"

write_secret_file sonar-db.vars "POSTGRES_PASSWORD=$sonar_db_pw"
write_secret_file sonarqube.vars "SONAR_JDBC_PASSWORD=$sonar_db_pw"
write_secret_file dd-db.vars "POSTGRES_PASSWORD=$dd_db_pw"
write_secret_file defectdojo.vars "$(cat <<EOF
DD_SECRET_KEY=$(rand 32)
DD_CREDENTIAL_AES_256_KEY=$(rand 16)
DD_DATABASE_URL=postgresql://defectdojo:$dd_db_pw@dd-db:5432/defectdojo
DD_ADMIN_PASSWORD=$dd_admin_pw
EOF
)"
write_secret_file cli.vars "$(cat <<EOF
# Read by bin/scan. Tokens are filled in by: bin/scan --bootstrap
DD_URL=http://127.0.0.1:$DD_PORT
DD_ADMIN_USER=admin
DD_ADMIN_PASSWORD=$dd_admin_pw
DD_API_TOKEN=
SONAR_URL=http://127.0.0.1:$SONAR_PORT
SONAR_ADMIN_PASSWORD=$sonar_admin_pw
SONAR_TOKEN=
EOF
)"

# Non-secret compose settings. Paths are quoted: the macOS data root contains a space ("Application Support").
cat >"$ROOT/.env" <<EOF
# Generated by scripts/init.sh - non-secret settings only. Secrets live in the config directory (mode 600).
LABSEC_CONFIG_DIR="$CONFIG_DIR"
LABSEC_CACHE_DIR="$LABSEC_CACHE_DIR"
SONAR_PORT=$SONAR_PORT
DD_PORT=$DD_PORT
EOF
chmod 644 "$ROOT/.env"
echo "written  $ROOT/.env (non-secret)"

echo
echo "Next: docker compose up -d && bin/scan --bootstrap && bin/scan --doctor"
