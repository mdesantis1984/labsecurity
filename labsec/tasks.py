"""Turn verified true positives into ODD task entries and close them after a re-run.

The generated block lives between markers inside an ODD task file of the analyzed project. Every task is keyed by
its DefectDojo finding id: re-running never duplicates, and text a human edited (inside a task or anywhere outside
the markers) is kept. LabSecurity never writes into another repository on its own: the caller names the file.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path

from labsec import knowledge, triage
from labsec.config import Paths
from labsec.dojo import DojoClient
from labsec.project import UsageError

SCHEMA = "labsec.tasks/v1"
BEGIN = "<!-- labsec:tasks:begin (managed by LabSecurity; keep each task between its own markers) -->"
END = "<!-- labsec:tasks:end -->"
DEFAULT_RELATIVE = Path("odd") / "tasks" / "security-findings.md"
HEADER = (
    "# Security findings\n\n"
    "Tasks generated by LabSecurity from true positives confirmed against the real code (DefectDojo is the source of truth).\n"
    "Order: Critical, High, Medium, Low. Critical and High block the PR. Mark a task done only through\n"
    "`labsec tasks <project> --close <dd-id> --commit <sha> --out <this file>` after a re-run shows the finding as closed.\n"
    "Text outside the managed block below is yours; it is never rewritten.\n"
)
_TASK = re.compile(
    r"<!-- labsec:task id=(?P<id>\d+) sev=(?P<sev>\w+) -->\n(?P<body>.*?)<!-- /labsec:task id=(?P=id) -->\n?",
    re.DOTALL,
)
_BLOCK = re.compile(re.escape(BEGIN.split(" (")[0]) + r".*?-->\n(?P<inner>.*?)" + re.escape(END) + r"\n?", re.DOTALL)
SHA = re.compile(r"^[0-9a-fA-F]{7,40}$")
_SEV_RANK = {name: index for index, name in enumerate(triage.SEVERITIES)}


# ----------------------------------------------------------------------------- selection
def true_positives(dojo: DojoClient, slug: str) -> list[dict]:
    """Active, non-duplicate findings tagged as confirmed true positives (views, ordered Critical first)."""
    product = triage.product_of(dojo, slug)
    raw = dojo.findings(
        test__engagement__product=product["id"], active="true", duplicate="false", tags=triage.TAG_TP
    )
    raw = [f for f in raw if triage.triage_state(f) == "true-positive" and f.get("active")]
    raw.sort(key=triage.sort_key)
    out = []
    for finding in raw:
        view = triage.view_of(dojo, finding)
        mitigation = str(finding.get("mitigation") or "") if view["tool"] == "trivy" else ""
        view["mitigation"] = " ".join(mitigation.split())[:200] or None
        out.append(view)
    return out


# ----------------------------------------------------------------------------- rendering
def _where(view: dict) -> str:
    return triage.where(view)


def render_task(view: dict) -> str:
    cat = knowledge.category(view)
    cwe = knowledge.effective_cwe(view)
    rule = view.get("rule")
    classification = []
    if rule:
        classification.append(f"rule `{rule}`")
    if cwe:
        label = knowledge.CWE_LABELS.get(cwe)
        classification.append(f"CWE-{cwe}" + (f" ({label})" if label else ""))
    classification_text = ", ".join(classification) or f"{view['tool']} finding"
    fix = knowledge.FIXES[cat]
    if cat == "dependency" and view.get("mitigation"):
        fix += f" Reported remediation: {view['mitigation']}"
    proof_hint = knowledge.PROOFS.get(cat)
    proof = f"Test-first: {knowledge.TEST_FIRST}"
    proof += f" (for example, {proof_hint})." if proof_hint else "."
    cli = Paths.from_env().root / "bin"
    lines = [
        f"- [ ] SEC-{view['id']} - {view['severity']} - {knowledge.explanation(view)} - `{_where(view)}`",
        f"  - DefectDojo finding: #{view['id']} <{view['url']}>",
        f"  - Severity: {view['severity']}" + (" (blocks the PR)" if view["severity"] in ("Critical", "High") else ""),
        f"  - Location: `{_where(view)}` ({view['tool']})",
        f"  - Rule / CWE: {classification_text}",
        f"  - Proposed fix: {fix}",
        f"  - {proof}",
        f"  - Authorization: {knowledge.AUTHORIZATION}.",
        f"  - Close the cycle: after the fix re-run `{cli}/scan <project>`; `{cli}/labsec verify-closed <project> {view['id']}` "
        f"must show it mitigated; then `{cli}/labsec tasks <project> --close {view['id']} --commit <sha> --out <this file>`.",
    ]
    return "\n".join(lines)


def _segment(view: dict) -> str:
    return f"<!-- labsec:task id={view['id']} sev={view['severity']} -->\n{render_task(view)}\n<!-- /labsec:task id={view['id']} -->\n"


def _parse_block(text: str):
    """Return (before, existing {id: (sev, segment text)}, after) for a document with a managed block."""
    match = _BLOCK.search(text)
    if not match:
        return None
    existing = {}
    for task in _TASK.finditer(match.group("inner")):
        existing[int(task.group("id"))] = (task.group("sev"), task.group(0).rstrip("\n") + "\n")
    return text[: match.start()], existing, text[match.end():]


def _compose_block(entries: dict[int, tuple[str, str]]) -> str:
    ordered = sorted(entries.items(), key=lambda kv: (_SEV_RANK.get(kv[1][0], 99), kv[0]))
    return BEGIN + "\n" + "".join(segment for _, (_, segment) in ordered) + END + "\n"


def merge_document(existing: str | None, views: list[dict]) -> tuple[str, list[int], list[int]]:
    """Return (new document text, added ids, kept ids). Idempotent: running twice yields identical text."""
    parsed = _parse_block(existing) if existing else None
    entries: dict[int, tuple[str, str]] = dict(parsed[1]) if parsed else {}
    added, kept = [], []
    for view in views:
        if view["id"] in entries:
            kept.append(view["id"])
            continue
        entries[view["id"]] = (view["severity"], _segment(view))
        added.append(view["id"])
    block = _compose_block(entries)
    if parsed:
        before, _, after = parsed
        text = before + block + after
    elif existing:
        marker = re.search(r"^## Log\s*$", existing, re.MULTILINE)
        if marker:  # keep the Log at the end of an ODD feature document
            text = existing[: marker.start()] + block + "\n" + existing[marker.start():]
        else:
            text = existing.rstrip("\n") + "\n\n" + block
    else:
        text = HEADER + "\n" + block
    return text, added, kept


def close_in_document(text: str, finding_id: int, sha: str, date: str) -> tuple[str, bool]:
    """Tick the task of `finding_id` and record the fix commit. Returns (text, changed)."""
    for match in _TASK.finditer(text):
        if int(match.group("id")) != finding_id:
            continue
        segment = match.group(0)
        if "- [x] SEC-" in segment:
            return text, False
        ticked = segment.replace("- [ ] SEC-", "- [x] SEC-", 1)
        closing = f"<!-- /labsec:task id={finding_id} -->"
        ticked = ticked.replace(
            closing, f"  - Done: fix commit {sha}; DefectDojo shows the finding as mitigated ({date}).\n{closing}", 1
        )
        return text[: match.start()] + ticked + text[match.end():], True
    raise UsageError(f"no LabSecurity task for DefectDojo finding {finding_id} in the document")


# ----------------------------------------------------------------------------- commands
def target_path(project_path: Path | None, out: str | None, feature_doc: str | None) -> tuple[Path | None, bool]:
    """(path, explicit). Only an explicitly named file is ever written; the default is read-only (dry run)."""
    if out:
        return Path(out).expanduser(), True
    if feature_doc:
        return Path(feature_doc).expanduser(), True
    if project_path is not None:
        return project_path / DEFAULT_RELATIVE, False
    return None, False


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.labsec-tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def generate(dojo: DojoClient, slug: str, project_path: Path | None, *, out=None, feature_doc=None, dry_run=False) -> dict:
    path, explicit = target_path(project_path, out, feature_doc)
    if feature_doc and not Path(feature_doc).expanduser().is_file():
        raise UsageError(f"feature document not found: {feature_doc}")
    views = true_positives(dojo, slug)
    existing = path.read_text(encoding="utf-8") if path and path.is_file() else None
    text, added, kept = merge_document(existing, views)
    write = explicit and not dry_run
    if write:
        _write(path, text)
    return {
        "schema": SCHEMA,
        "project": slug,
        "target": str(path) if path else None,
        "mode": "written" if write else "dry-run",
        "added": added,
        "kept": kept,
        "true_positives": len(views),
        "changed": text != (existing or ""),
        "content": text,
    }


def render_generate_text(result: dict, *, with_content: bool) -> str:
    head = (
        f"{result['mode']}: {result['project']} -> {result['target'] or '(no target; pass --out)'} | "
        f"{result['true_positives']} true positive(s), {len(result['added'])} added, {len(result['kept'])} already there"
    )
    if result["mode"] == "dry-run":
        head += " | nothing written (pass --out <file> to write)"
    return head + ("\n\n" + result["content"] if with_content else "")


def close_task(dojo: DojoClient, slug: str, finding_id: int, commit: str, path: Path | None, *, dry_run: bool, explicit: bool) -> dict:
    """Mark the task done only when DefectDojo shows the finding as mitigated."""
    if not SHA.match(commit or ""):
        raise UsageError("--commit must be a git commit hash (7-40 hex characters)")
    state = verify_one(dojo, finding_id)
    if state["state"] != "mitigated":
        raise TaskNotClosable(
            f"finding {finding_id} is {state['state']} in DefectDojo, not mitigated: fix it, re-run `bin/scan`, then retry",
            state,
        )
    if path is None or not path.is_file():
        raise UsageError(f"task document not found: {path}")
    original = path.read_text(encoding="utf-8")
    date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    text, changed = close_in_document(original, finding_id, commit.lower(), date)
    write = explicit and not dry_run and changed
    if write:
        _write(path, text)
    return {
        "schema": SCHEMA,
        "project": slug,
        "target": str(path),
        "mode": "written" if write else "dry-run",
        "closed": finding_id if changed else None,
        "already_closed": not changed,
        "commit": commit.lower(),
        "content": text,
    }


class TaskNotClosable(RuntimeError):
    def __init__(self, message: str, state: dict):
        super().__init__(message)
        self.state = state


# ----------------------------------------------------------------------------- verify-closed
VERIFY_SCHEMA = "labsec.verify/v1"


def verify_one(dojo: DojoClient, finding_id: int) -> dict:
    from labsec.dojo import DojoNotFound

    try:
        finding = dojo.get_finding(finding_id)
    except DojoNotFound:
        return {"id": finding_id, "state": "not-found"}
    if finding.get("risk_accepted"):
        state = "risk-accepted"
    elif finding.get("false_p"):
        state = "false-positive"
    elif finding.get("is_mitigated"):
        state = "mitigated"
    elif finding.get("duplicate"):
        state = "duplicate"
    else:
        state = "open"
    return {
        "id": finding_id,
        "state": state,
        "severity": finding.get("severity"),
        "file": finding.get("file_path"),
        "line": finding.get("line"),
        "mitigated_at": finding.get("mitigated"),
    }


def verify_closed(dojo: DojoClient, slug: str, ids: list[int]) -> dict:
    results = [verify_one(dojo, i) for i in ids]
    return {
        "schema": VERIFY_SCHEMA,
        "project": slug,
        "all_mitigated": all(r["state"] == "mitigated" for r in results),
        "results": results,
    }


def render_verify_text(data: dict) -> str:
    lines = [f"{data['project']}: " + ("all findings are mitigated" if data["all_mitigated"] else "NOT all findings are mitigated")]
    for item in data["results"]:
        location = ""
        if item.get("file"):
            location = f" {item['file']}" + (f":{item['line']}" if item.get("line") else "")
        lines.append(f"#{item['id']} {item['state']}{location}" + (f" ({item['severity']})" if item.get("severity") else ""))
    return "\n".join(lines)
